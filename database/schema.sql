CREATE TABLE IF NOT EXISTS players (
  id SERIAL PRIMARY KEY,
  username VARCHAR(24) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS game_progress (
  player_id INTEGER PRIMARY KEY REFERENCES players(id) ON DELETE CASCADE,
  current_map VARCHAR(40) NOT NULL DEFAULT 'vilarejo',
  player_x INTEGER NOT NULL DEFAULT 2,
  player_y INTEGER NOT NULL DEFAULT 5,
  level INTEGER NOT NULL DEFAULT 5,
  xp INTEGER NOT NULL DEFAULT 0,
  hp INTEGER NOT NULL DEFAULT 35,
  max_hp INTEGER NOT NULL DEFAULT 35,
  secret_item BOOLEAN NOT NULL DEFAULT FALSE,
  gym1_won BOOLEAN NOT NULL DEFAULT FALSE,
  gym2_won BOOLEAN NOT NULL DEFAULT FALSE,
  good_ending BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS matches (
  id SERIAL PRIMARY KEY,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  points INTEGER NOT NULL DEFAULT 0,
  ending VARCHAR(20) NOT NULL DEFAULT 'incomplete',
  duration_seconds INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_matches_points ON matches(points DESC);
